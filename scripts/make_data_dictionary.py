"""Generate docs/DATA_DICTIONARY.md from the live warehouse schema plus the grain comments in sql/schema.sql."""

from __future__ import annotations

import re
import sys

from rice_market import config
from rice_market import data_access as da

STATUS_NOTES = {
    "status": "'reported' = value published by the source; 'missing' = month inside the span with no value (never zero)",
    "is_complete": "TRUE only when all 12 months of the year are reported",
    "net_wgt_t": "net weight in metric tons (Comtrade netWgt kg / 1000)",
    "fob_usd": "free-on-board value, US$ (Comtrade fobvalue, falling back to primaryValue)",
    "cif_usd": "cost-insurance-freight value, US$ (importers' reports)",
    "usd_per_tonne": "nominal US$ per metric ton (Pink Sheet); NULL where the source is blank or an error cell",
    "tonnes": "metric tons",
}


def grain_text(raw: str | None) -> str:
    return (raw or "").removeprefix("grain: ") or "see sql/schema.sql"


def main() -> int:
    sql = (config.ROOT / "sql" / "schema.sql").read_text(encoding="utf-8")
    grains = {
        m.group(1): (m.group(2) or "").strip() for m in re.finditer(r"CREATE TABLE (\w+) \(\s*(?:--\s*(.*))?", sql)
    }
    con = da.connect(config.DEMO_DB_PATH)  # schema only; the demo warehouse holds synthetic values
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/make_data_dictionary.py` from the schema of the synthetic demonstration warehouse (no values).",
        "",
    ]
    tables = [r[0] for r in con.execute("SELECT table_name FROM information_schema.tables ORDER BY 1").fetchall()]
    for t in tables:
        pk = con.execute(
            "SELECT constraint_column_names FROM duckdb_constraints() WHERE table_name = ? AND constraint_type = 'PRIMARY KEY'",
            [t],
        ).fetchone()
        lines += [
            f"## `{t}`",
            "",
            f"Grain: {grain_text(grains.get(t))}  ",
            f"Primary key: {', '.join(pk[0]) if pk else 'none'}  ",
            "",
            "| Column | Type | Note |",
            "|---|---|---|",
        ]
        for name, typ in con.execute(
            "SELECT column_name, data_type FROM information_schema.columns WHERE table_name = ? ORDER BY ordinal_position",
            [t],
        ).fetchall():
            lines.append(f"| {name} | {typ} | {STATUS_NOTES.get(name, '')} |")
        lines.append("")
    (config.ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote docs/DATA_DICTIONARY.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
